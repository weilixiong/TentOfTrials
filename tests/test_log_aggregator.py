#!/usr/bin/env python3
"""
Independent validation tests for tools/log_aggregator.py.

Per the tool's own TODO comment, its existing parser test data (if any) was
generated by the same parser code it tests, giving a high false-pass rate.
These tests instead use hand-written fixtures (tests/fixtures/log_samples.py)
based on public log-format conventions, so they can actually catch
regressions in timestamp, level, service, and key-field extraction.

Run with:
    python3 tests/test_log_aggregator.py
    python3 -m unittest tests.test_log_aggregator
"""

import os
import subprocess
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from tools.log_aggregator import (
    JSONLogParser,
    TextLogParser,
    NginxLogParser,
    LogAggregator,
)
from tests.fixtures.log_samples import JSON_SAMPLES, TEXT_SAMPLES, NGINX_SAMPLES


class JSONLogParserTests(unittest.TestCase):
    def setUp(self):
        self.parser = JSONLogParser()

    def test_samples(self):
        for sample in JSON_SAMPLES:
            with self.subTest(sample["name"]):
                entry = self.parser.parse(sample["line"])
                expect = sample["expect"]
                if expect is None:
                    self.assertIsNone(entry, sample["name"])
                    continue
                self.assertIsNotNone(entry, sample["name"])
                self.assertEqual(entry["timestamp"], expect["timestamp"])
                self.assertEqual(entry["level"], expect["level"])
                self.assertEqual(entry["service"], expect["service"])
                self.assertEqual(entry["message"], expect["message"])
                self.assertEqual(entry["format"], expect["format"])


class TextLogParserTests(unittest.TestCase):
    def setUp(self):
        self.parser = TextLogParser()

    def test_samples(self):
        for sample in TEXT_SAMPLES:
            with self.subTest(sample["name"]):
                entry = self.parser.parse(sample["line"])
                expect = sample["expect"]
                if expect is None:
                    self.assertIsNone(entry, sample["name"])
                    continue
                self.assertIsNotNone(entry, sample["name"])
                self.assertEqual(entry["level"], expect["level"])
                self.assertEqual(entry["format"], expect["format"])
                if expect.get("has_timestamp"):
                    self.assertIsNotNone(entry["timestamp"], sample["name"])
                else:
                    self.assertIsNone(entry["timestamp"], sample["name"])
                if "service" in expect:
                    self.assertEqual(entry["service"], expect["service"])


class NginxLogParserTests(unittest.TestCase):
    def setUp(self):
        self.parser = NginxLogParser()

    def test_samples(self):
        for sample in NGINX_SAMPLES:
            with self.subTest(sample["name"]):
                entry = self.parser.parse(sample["line"])
                expect = sample["expect"]
                if expect is None:
                    self.assertIsNone(entry, sample["name"])
                    continue
                self.assertIsNotNone(entry, sample["name"])
                self.assertEqual(entry["level"], expect["level"])
                self.assertEqual(entry["service"], expect["service"])
                self.assertEqual(entry["format"], expect["format"])
                self.assertEqual(entry["fields"]["status"], expect["status"])
                self.assertEqual(entry["fields"]["remote_addr"], expect["remote_addr"])
                self.assertEqual(entry["fields"]["remote_user"], expect["remote_user"])
                if expect.get("has_timestamp"):
                    self.assertIsNotNone(entry["timestamp"], sample["name"])

    def test_malformed_line_is_rejected_by_nginx_parser_specifically(self):
        # Cross-format guard: TextLogParser matches almost anything, so this
        # confirms NginxLogParser itself correctly rejects non-nginx input
        # rather than silently matching garbage.
        self.assertIsNone(self.parser.parse("not a valid nginx log line at all"))


class LogAggregatorPipelineTests(unittest.TestCase):
    """Exercises the full parser-selection pipeline (LogAggregator._parse_line),
    which is where format precedence bugs actually surface -- a parser can be
    individually correct but never get a chance to run if an earlier parser
    in the pipeline greedily claims lines it shouldn't."""

    def test_nginx_lines_are_routed_to_the_nginx_parser(self):
        agg = LogAggregator()
        nginx_line = NGINX_SAMPLES[0]["line"]
        self.assertTrue(agg._parse_line(nginx_line + "\n"))
        entry = agg.entries[0]
        self.assertEqual(entry["format"], "nginx")
        self.assertEqual(entry["service"], "nginx")
        self.assertIsNotNone(entry["timestamp"])

    def test_json_lines_are_routed_to_the_json_parser(self):
        agg = LogAggregator()
        json_line = JSON_SAMPLES[0]["line"]
        self.assertTrue(agg._parse_line(json_line + "\n"))
        self.assertEqual(agg.entries[0]["format"], "json")

    def test_plain_text_lines_are_routed_to_the_text_parser(self):
        agg = LogAggregator()
        text_line = TEXT_SAMPLES[0]["line"]
        self.assertTrue(agg._parse_line(text_line + "\n"))
        self.assertEqual(agg.entries[0]["format"], "text")

    def test_malformed_lines_from_every_format_do_not_crash_the_pipeline(self):
        agg = LogAggregator()
        malformed_lines = (
            [s["line"] for s in JSON_SAMPLES if s["expect"] is None]
            + [s["line"] for s in NGINX_SAMPLES if s["expect"] is None]
        )
        for line in malformed_lines:
            with self.subTest(line=line):
                try:
                    agg._parse_line(line + "\n")
                except Exception as exc:  # pragma: no cover - failure path
                    self.fail(f"_parse_line crashed on {line!r}: {exc!r}")

    def test_json_string_timestamp_does_not_crash_summary(self):
        # Regression test: JSON logs commonly carry ISO8601 *string*
        # timestamps. get_summary()/_get_time_range() must not raise even
        # though the aggregator's hourly histogram only understands
        # numeric unix timestamps.
        agg = LogAggregator()
        string_ts_sample = next(
            s for s in JSON_SAMPLES if s["name"] == "string_iso_timestamp_common_real_world_case"
        )
        agg._parse_line(string_ts_sample["line"] + "\n")
        try:
            summary = agg.get_summary()
        except Exception as exc:  # pragma: no cover - failure path
            self.fail(f"get_summary() crashed on a string timestamp: {exc!r}")
        self.assertEqual(summary["total_entries"], 1)
        self.assertEqual(summary["by_level"].get("critical"), 1)

    def test_mixed_format_file_end_to_end(self):
        """Simulates the documented CLI usage against a single file containing
        all three formats plus malformed lines, mirroring how the aggregator
        is actually invoked in production.

        Note: TextLogParser is an intentional catch-all that accepts any
        non-empty line, so a line that fails JSON/nginx parsing (e.g.
        `{not valid json at all,,,`) still gets captured as a generic text
        entry rather than being dropped -- only genuinely empty/whitespace
        lines are dropped entirely. That is existing, by-design behavior,
        not something this change alters.
        """
        all_samples = JSON_SAMPLES + TEXT_SAMPLES + NGINX_SAMPLES
        lines = [s["line"] for s in all_samples]
        unparseable_count = sum(1 for s in all_samples if not s["line"].strip())
        expected_parsed = len(all_samples) - unparseable_count

        expected_json = sum(1 for s in JSON_SAMPLES if s["expect"] is not None)
        expected_nginx = sum(1 for s in NGINX_SAMPLES if s["expect"] is not None)
        expected_text = expected_parsed - expected_json - expected_nginx

        with tempfile.NamedTemporaryFile(
            mode="w", suffix=".log", delete=False
        ) as f:
            f.write("\n".join(lines) + "\n")
            path = f.name

        try:
            agg = LogAggregator()
            parsed = agg.process_file(path)
            self.assertEqual(parsed, expected_parsed)

            format_counts = {"json": 0, "nginx": 0, "text": 0}
            for entry in agg.entries:
                format_counts[entry["format"]] += 1
            self.assertEqual(format_counts["json"], expected_json)
            self.assertEqual(format_counts["nginx"], expected_nginx)
            self.assertEqual(format_counts["text"], expected_text)

            summary = agg.get_summary()
            self.assertEqual(summary["total_entries"], expected_parsed)
            self.assertIn("nginx", summary["by_service"])
            self.assertEqual(summary["by_service"]["nginx"], expected_nginx)
        finally:
            os.unlink(path)


class CLICompatibilityTests(unittest.TestCase):
    """Confirms the documented CLI entry point still works end-to-end after
    the parser-precedence and timestamp-type fixes."""

    def test_cli_runs_against_mixed_format_file(self):
        repo_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        script = os.path.join(repo_root, "tools", "log_aggregator.py")

        all_samples = JSON_SAMPLES + TEXT_SAMPLES + NGINX_SAMPLES
        lines = [s["line"] for s in all_samples]

        with tempfile.TemporaryDirectory() as tmpdir:
            input_path = os.path.join(tmpdir, "sample.log")
            output_path = os.path.join(tmpdir, "report.json")
            with open(input_path, "w") as f:
                f.write("\n".join(lines) + "\n")

            result = subprocess.run(
                [
                    sys.executable,
                    script,
                    "--input",
                    input_path,
                    "--output",
                    output_path,
                ],
                capture_output=True,
                text=True,
                timeout=30,
            )

            self.assertEqual(
                result.returncode, 0,
                f"CLI exited non-zero.\nstdout:\n{result.stdout}\nstderr:\n{result.stderr}",
            )
            self.assertTrue(os.path.exists(output_path))


if __name__ == "__main__":
    unittest.main()
