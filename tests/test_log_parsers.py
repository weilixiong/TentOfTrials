class TestNginxLogParser(unittest.TestCase):
    """Validate NginxLogParser against independent fixtures."""

    def setUp(self):
        self.parser = NginxLogParser()

    def test_parse_valid_nginx_entries(self):
        """All valid nginx fixtures should produce non-None results."""
        for i, line in enumerate(NGINX_VALID_ENTRIES):
            result = self.parser.parse(line)
            assert result is not None, f"Nginx fixture {i} should parse successfully"
            assert result.get('format') == 'nginx', f"Nginx fixture {i} format should be 'nginx'"

    def test_nginx_extracts_remote_addr(self):
        result = self.parser.parse(NGINX_VALID_ENTRIES[0])
        assert result['fields']['remote_addr'] == '192.168.1.100'

    def test_nginx_extracts_request(self):
        result = self.parser.parse(NGINX_VALID_ENTRIES[0])
        assert result['message'] == 'GET /api/users HTTP/1.1'
        assert result['fields']['request'] == 'GET /api/users HTTP/1.1'

    def test_nginx_status_200_is_info(self):
        result = self.parser.parse(NGINX_VALID_ENTRIES[0])
        assert result['level'] == 'info'
        assert result['fields']['status'] == 200

    def test_nginx_status_500_is_error(self):
        result = self.parser.parse(NGINX_VALID_ENTRIES[2])
        assert result['level'] == 'error'
        assert result['fields']['status'] == 500

    def test_nginx_status_404_is_warn(self):
        result = self.parser.parse(NGINX_VALID_ENTRIES[3])
        assert result['level'] == 'warn'
        assert result['fields']['status'] == 404

    def test_nginx_status_301_is_info(self):
        """Parser maps only >=400 to warn; 3xx redirects stay info."""
        result = self.parser.parse(NGINX_VALID_ENTRIES[4])
        assert result['level'] == 'info'

    def test_nginx_extracts_user(self):
        """Parser maps the 2nd whitespace token to 'remote_user'.

        In standard combined format that slot holds the identd logname
        ('-' when absent); the authenticated user (3rd token) is not
        surfaced as a field — documented actual behavior.
        """
        result = self.parser.parse(NGINX_VALID_ENTRIES[5])
        assert result['fields']['remote_user'] == '-'

    def test_nginx_service_always_nginx(self):
        for line in NGINX_VALID_ENTRIES:
            result = self.parser.parse(line)
            assert result['service'] == 'nginx'

    def test_nginx_malformed_does_not_crash(self):
        """Malformed nginx lines must never raise; most return None."""
        for i, line in enumerate(NGINX_MALFORMED_ENTRIES):
            try:
                result = self.parser.parse(line)
                # Unparseable garbage returns None; structurally-close lines
                # may parse with degraded fields (covered by bad-date test).
                if i in (0, 1, 3):
                    assert result is None, f"Malformed nginx fixture {i} should return None, got {result}"
            except Exception as e:
                raise AssertionError(f"Nginx fixture {i} crashed parser: {e}")

    def test_nginx_bad_date_does_not_crash(self):
        """Nginx line with unparseable date should still parse (timestamp=None) but not crash."""
        result = self.parser.parse(NGINX_MALFORMED_ENTRIES[2])
        # May return None if regex doesn't match at all, or result with timestamp=None
        # Either way, must not raise an exception
        assert result is None or result.get('timestamp') is None


