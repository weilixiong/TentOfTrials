class TestTextLogParser(unittest.TestCase):
    """Validate TextLogParser against independent fixtures."""

    def setUp(self):
        self.parser = TextLogParser()

    def test_parse_valid_text_entries(self):
        """All valid text fixtures should produce non-None results."""
        for i, line in enumerate(TEXT_VALID_ENTRIES):
            result = self.parser.parse(line)
            assert result is not None, f"Text fixture {i} should parse successfully"
            assert result.get('format') == 'text', f"Text fixture {i} format should be 'text'"

    def test_text_extracts_timestamp_iso8601(self):
        """ISO 8601 timestamps should be extracted as unix epoch."""
        result = self.parser.parse(TEXT_VALID_ENTRIES[0])  # 2024-03-14T08:15:33
        assert result['timestamp'] is not None
        # March 14 2024 ~1710417333 epoch
        assert result['timestamp'] > 1710000000  # roughly correct era

    def test_text_extracts_timestamp_syslog(self):
        """Syslog-style timestamps should also be extracted."""
        result = self.parser.parse(TEXT_VALID_ENTRIES[2])  # Mar 14 10:05:00
        assert result['timestamp'] is not None

    def test_text_extracts_level_error(self):
        """ERROR/FATAL/CRITICAL should map to 'error'."""
        result = self.parser.parse(TEXT_VALID_ENTRIES[0])
        assert result['level'] == 'error'

        fatal = self.parser.parse(TEXT_VALID_ENTRIES[4])
        assert fatal['level'] == 'error'

    def test_text_extracts_level_warn(self):
        """WARNING/WARN should map to 'warn'."""
        result = self.parser.parse(TEXT_VALID_ENTRIES[1])
        assert result['level'] == 'warn'

    def test_text_extracts_level_info(self):
        """INFO/NOTICE should map to 'info'."""
        result = self.parser.parse(TEXT_VALID_ENTRIES[2])
        assert result['level'] == 'info'

    def test_text_extracts_level_debug(self):
        """DEBUG/TRACE should map to 'debug'."""
        result = self.parser.parse(TEXT_VALID_ENTRIES[3])
        assert result['level'] == 'debug'

    def test_text_extracts_service_from_brackets(self):
        """Service in [brackets] should be extracted."""
        result = self.parser.parse(TEXT_VALID_ENTRIES[0])
        assert result['service'] == 'gateway'

    def test_text_extracts_service_from_colon(self):
        """Service from UPPERCASE: prefix should be extracted.

        Note: the parser only inspects the FIRST \\w+: occurrence and
        requires .isupper() — timestamps containing 'T' can shadow the
        real service token, so this fixture has no leading timestamp.
        """
        result = self.parser.parse('DB: Slow query detected (elapsed=2400ms)')
        assert result['service'] == 'DB'

    def test_text_malformed_does_not_crash(self):
        """Malformed text lines should return None or a result with unknown level — never crash."""
        for i, line in enumerate(TEXT_MALFORMED_ENTRIES):
            try:
                result = self.parser.parse(line)
                # Empty/whitespace lines may return None
                if line.strip():
                    # Unparseable but non-empty should still produce a result (with unknown level)
                    assert result is not None, f"Text fixture {i} should produce a result"
                    assert result.get('level') == 'unknown', f"Unparseable text fixture {i} should have level=unknown"
            except Exception as e:
                raise AssertionError(f"Text fixture {i} crashed parser: {e}")

    def test_text_preserves_raw_message(self):
        """Raw message should be stored in fields.raw."""
        result = self.parser.parse(TEXT_VALID_ENTRIES[0])
        assert result['fields']['raw'] == TEXT_VALID_ENTRIES[0]


