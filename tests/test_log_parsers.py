class TestJSONLogParser(unittest.TestCase):
    """Validate JSONLogParser against independent fixtures."""

    def setUp(self):
        self.parser = JSONLogParser()

    def test_parse_valid_json_entries(self):
        """All valid JSON fixtures should produce non-None results with correct format."""
        for i, line in enumerate(JSON_VALID_ENTRIES):
            result = self.parser.parse(line)
            assert result is not None, f"JSON fixture {i} should parse successfully"
            assert result.get('format') == 'json', f"JSON fixture {i} format should be 'json'"

    def test_json_extracts_timestamp(self):
        """Entries with timestamp field should preserve it."""
        result = self.parser.parse(JSON_VALID_ENTRIES[0])
        assert result['timestamp'] == '2024-03-15T10:23:45.123Z'

    def test_json_extracts_level(self):
        """Level field should be extracted; fallback to 'info' if missing."""
        error_entry = self.parser.parse(JSON_VALID_ENTRIES[0])
        assert error_entry['level'] == 'error'

        no_level = self.parser.parse(JSON_VALID_ENTRIES[2])  # minimal entry
        assert no_level['level'] == 'info'  # default fallback

    def test_json_extracts_service(self):
        """Service/logger field should be extracted."""
        result = self.parser.parse(JSON_VALID_ENTRIES[0])
        assert result['service'] == 'auth-api'

        # Alternative field name 'logger'
        alt = self.parser.parse(JSON_VALID_ENTRIES[1])
        assert alt['service'] == 'payment-service'

    def test_json_extracts_message(self):
        """Message/msg/event field should be extracted."""
        result = self.parser.parse(JSON_VALID_ENTRIES[0])
        assert 'Login failed' in result['message']

    def test_json_malformed_returns_none(self):
        """Malformed/non-JSON lines should return None without crashing."""
        for i, line in enumerate(JSON_MALFORMED_ENTRIES):
            result = self.parser.parse(line)
            assert result is None, f"Malformed JSON fixture {i} should return None, got {result}"

    def test_json_empty_object_returns_default_entry(self):
        """An empty JSON object parses to a default entry (level=info, empty message)."""
        result = self.parser.parse('{}')
        assert result is not None
        assert result['format'] == 'json'
        assert result['message'] == ''
        assert result['level'] == 'info' 

    def test_json_array_not_parsed(self):
        """A JSON array (not object) should return None."""
        result = self.parser.parse(JSON_MALFORMED_ENTRIES[3])
        assert result is None


