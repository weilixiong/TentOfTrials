class TestLogAggregatorIntegration(unittest.TestCase):
    """Verify the full aggregation pipeline accepts all fixture types."""

    def setUp(self):
        from log_aggregator import LogAggregator
        self.aggregator = LogAggregator()

    def test_aggregator_processes_all_json_fixtures(self):
        count = 0
        for line in JSON_VALID_ENTRIES:
            if self.aggregator._parse_line(line):
                count += 1
        assert count == len(JSON_VALID_ENTRIES), f"Expected {len(JSON_VALID_ENTRIES)} JSON entries parsed, got {count}"

    def test_aggregator_processes_all_nginx_fixtures(self):
        count = 0
        for line in NGINX_VALID_ENTRIES:
            if self.aggregator._parse_line(line):
                count += 1
        assert count == len(NGINX_VALID_ENTRIES), f"Expected {len(NGINX_VALID_ENTRIES)} nginx entries parsed, got {count}"

    def test_aggregator_skips_malformed_lines(self):
        """Malformed lines from all formats should be silently skipped (no crash)."""
        all_malformed = JSON_MALFORMED_ENTRIES + TEXT_MALFORMED_ENTRIES + NGINX_MALFORMED_ENTRIES
        for line in all_malformed:
            try:
                self.aggregator._parse_line(line)
            except Exception as e:
                raise AssertionError(f"Aggregator crashed on malformed line: {line!r} -> {e}")


