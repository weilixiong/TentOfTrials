"""Independent parser fixtures for tools/log_aggregator.py (issue #5).

Fixture lines are hand-written from the public formats they represent;
none of them were generated by the parser under test. The nginx-variant
cases cover a clear bug exposed by these fixtures: nginx combined-log
lines with a '-' body_bytes value, and nginx common-log lines without
referer/user_agent, were silently misclassified as plain text (the
permissive text parser ran before the nginx parser in LogAggregator,
and the nginx pattern itself rejected both shapes).
"""

import sys
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from tools.log_aggregator import (  # noqa: E402
    JSONLogParser,
    LogAggregator,
    NginxLogParser,
    TextLogParser,
)

FIXTURE_ROOT = Path(__file__).parent / "fixtures" / "parser_independent"


def fixture_lines(name):
    return [
        line.strip()
        for line in (FIXTURE_ROOT / name).read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]


class NginxVariantTests(unittest.TestCase):
    def test_combined_log_lines_parse_as_nginx(self):
        parser = NginxLogParser()
        entries = [parser.parse(line) for line in fixture_lines("access.nginx.log")[:3]]
        self.assertTrue(all(entry is not None for entry in entries))
        self.assertEqual(entries[0]["format"], "nginx")
        self.assertEqual(entries[0]["service"], "nginx")
        self.assertEqual(entries[0]["level"], "info")
        self.assertEqual(entries[0]["fields"]["status"], 200)
        self.assertEqual(entries[0]["fields"]["remote_addr"], "203.0.113.10")
        self.assertEqual(entries[1]["level"], "error")  # 503
        self.assertEqual(entries[2]["level"], "warn")  # 404

    def test_dash_body_bytes_parses_as_zero(self):
        parser = NginxLogParser()
        entry = parser.parse(fixture_lines("access.nginx.log")[3])
        self.assertIsNotNone(entry)
        self.assertEqual(entry["format"], "nginx")
        self.assertEqual(entry["fields"]["status"], 200)
        self.assertEqual(entry["fields"]["body_bytes"], 0)

    def test_common_log_without_referer_or_user_agent_parses(self):
        parser = NginxLogParser()
        entry = parser.parse(fixture_lines("access.nginx.log")[4])
        self.assertIsNotNone(entry)
        self.assertEqual(entry["format"], "nginx")
        self.assertEqual(entry["fields"]["status"], 200)
        self.assertEqual(entry["fields"]["body_bytes"], 512)
        self.assertEqual(entry["fields"]["referer"], "-")
        self.assertEqual(entry["fields"]["user_agent"], "-")

    def test_aggregator_classifies_nginx_lines_as_nginx(self):
        agg = LogAggregator()
        for line in fixture_lines("access.nginx.log"):
            agg._parse_line(line)
        self.assertEqual(len(agg.entries), 5)
        self.assertTrue(all(e["format"] == "nginx" for e in agg.entries))
        self.assertEqual(agg.service_counts["nginx"], 5)


class IndependentFixtureTests(unittest.TestCase):
    def test_json_text_and_nginx_fixtures_parse(self):
        json_entries = [JSONLogParser().parse(l) for l in fixture_lines("structured.jsonl")]
        self.assertTrue(all(e is not None for e in json_entries))
        self.assertEqual(json_entries[0]["service"], "payments")
        self.assertEqual(json_entries[0]["level"], "ERROR")
        text_entries = [TextLogParser().parse(l) for l in fixture_lines("plain_text.log")]
        self.assertTrue(all(e is not None for e in text_entries))
        self.assertEqual(text_entries[0]["service"], "gateway")
        self.assertEqual(text_entries[1]["level"], "warn")

    def test_malformed_lines_do_not_crash_aggregation(self):
        agg = LogAggregator()
        for line in fixture_lines("malformed.log"):
            agg._parse_line(line)  # must not raise
        summary = agg.get_summary()
        self.assertGreaterEqual(summary["total_entries"], 1)


if __name__ == "__main__":
    unittest.main()
