"""Independent fixture tests for tools/log_aggregator.py parsers.

The fixtures under ``tools/tests/fixtures/`` are hand-written representative
log lines and are NOT generated by the parser under test, so they validate the
parsers against independent input (the docstring in ``log_aggregator.py`` warns
that parser-generated samples can false-pass).

Run with::

    python3 -m unittest discover -s tools/tests -v

or::

    python3 tools/tests/test_log_aggregator_fixtures.py
"""

import json
import subprocess
import sys
import tempfile
import unittest
from datetime import datetime, timezone
from pathlib import Path

TOOLS_DIR = Path(__file__).resolve().parents[1]
FIXTURES_DIR = Path(__file__).resolve().parent / "fixtures"

sys.path.insert(0, str(TOOLS_DIR))

from log_aggregator import (  # noqa: E402
    JSONLogParser,
    LogAggregator,
    NginxLogParser,
    TextLogParser,
)


def read_fixture(name: str):
    """Return fixture lines; a trailing newline does not add a blank entry."""
    return (FIXTURES_DIR / name).read_text(encoding="utf-8").splitlines()


def epoch(year, month, day, hour, minute, second) -> int:
    return int(
        datetime(year, month, day, hour, minute, second, tzinfo=timezone.utc).timestamp()
    )


class JSONLogParserFixtureTests(unittest.TestCase):
    def setUp(self):
        self.parser = JSONLogParser()

    def test_fixture_lines_parse_with_expected_core_fields(self):
        entries = [self.parser.parse(line) for line in read_fixture("json_logs.log")]

        self.assertEqual(len(entries), 4)
        self.assertTrue(all(e is not None for e in entries))
        self.assertEqual([e["format"] for e in entries], ["json"] * 4)

        first = entries[0]
        self.assertEqual(first["timestamp"], epoch(2024, 3, 1, 12, 0, 0))
        self.assertEqual(first["level"], "INFO")
        self.assertEqual(first["service"], "auth")
        self.assertEqual(first["message"], "user alice logged in")

        second = entries[1]
        self.assertEqual(second["timestamp"], epoch(2024, 3, 1, 12, 1, 30))
        self.assertEqual(second["level"], "ERROR")
        self.assertEqual(second["service"], "payment")
        self.assertEqual(second["fields"]["order_id"], 42)

        third = entries[2]
        self.assertEqual(third["timestamp"], epoch(2024, 3, 1, 12, 2, 0))
        self.assertEqual(third["level"], "warn")
        self.assertEqual(third["service"], "gateway")
        self.assertEqual(third["fields"]["latency_ms"], 1500)

        fourth = entries[3]
        self.assertEqual(fourth["timestamp"], 1709294580)
        self.assertEqual(fourth["level"], "debug")
        self.assertEqual(fourth["service"], "cache")

    def test_timestamp_is_epoch_int_for_every_variant(self):
        for line in read_fixture("json_logs.log"):
            entry = self.parser.parse(line)
            self.assertIsInstance(
                entry["timestamp"], int, f"non-int timestamp for: {line!r}"
            )

    def test_non_json_line_is_rejected(self):
        self.assertIsNone(self.parser.parse("!! not json !!"))

    def test_broken_json_does_not_raise(self):
        self.assertIsNone(self.parser.parse('{"broken_json": '))


class TextLogParserFixtureTests(unittest.TestCase):
    def setUp(self):
        self.parser = TextLogParser()

    def test_bracketed_service_level_and_timestamp(self):
        entry = self.parser.parse("2024-03-01 12:00:00 [auth] INFO user alice logged in")
        self.assertEqual(entry["format"], "text")
        self.assertEqual(entry["timestamp"], epoch(2024, 3, 1, 12, 0, 0))
        self.assertEqual(entry["level"], "info")
        self.assertEqual(entry["service"], "auth")
        self.assertEqual(
            entry["message"], "2024-03-01 12:00:00 [auth] INFO user alice logged in"
        )

    def test_all_text_fixture_lines_parse(self):
        entries = [self.parser.parse(line) for line in read_fixture("text_logs.log")]
        self.assertEqual(len(entries), 5)
        self.assertTrue(all(e is not None for e in entries))
        self.assertEqual([e["format"] for e in entries], ["text"] * 5)
        self.assertEqual(entries[1]["level"], "error")
        self.assertEqual(entries[2]["level"], "warn")
        self.assertEqual(entries[4]["level"], "unknown")
        # Yearless syslog lines ("Mar  1 ...") resolve to year 1900 with the
        # existing parser; assert the fields it does recover, not the year.
        self.assertEqual(entries[3]["service"], "syslogd")
        self.assertEqual(entries[3]["level"], "debug")

    def test_blank_lines_rejected(self):
        self.assertIsNone(self.parser.parse(""))
        self.assertIsNone(self.parser.parse("   \t "))


class NginxLogParserFixtureTests(unittest.TestCase):
    def setUp(self):
        self.parser = NginxLogParser()

    def test_combined_access_log_fields(self):
        line = (
            '127.0.0.1 - - [01/Mar/2024:12:00:00 +0000] '
            '"GET /api/health HTTP/1.1" 200 612 "-" "curl/8.0.1"'
        )
        entry = self.parser.parse(line)
        self.assertIsNotNone(entry)
        self.assertEqual(entry["format"], "nginx")
        self.assertEqual(entry["service"], "nginx")
        self.assertEqual(entry["timestamp"], epoch(2024, 3, 1, 12, 0, 0))
        self.assertEqual(entry["level"], "info")
        self.assertEqual(entry["fields"]["remote_addr"], "127.0.0.1")
        self.assertEqual(entry["fields"]["status"], 200)
        self.assertEqual(entry["fields"]["request"], "GET /api/health HTTP/1.1")
        self.assertEqual(entry["fields"]["user_agent"], "curl/8.0.1")

    def test_fixture_status_maps_to_level(self):
        entries = [self.parser.parse(line) for line in read_fixture("nginx_logs.log")]
        self.assertEqual(len(entries), 4)
        self.assertEqual([e["level"] for e in entries], ["info", "info", "warn", "error"])
        self.assertEqual([e["fields"]["status"] for e in entries], [200, 302, 404, 500])
        self.assertEqual(
            [e["fields"]["remote_addr"] for e in entries],
            ["127.0.0.1", "10.0.0.5", "192.168.1.10", "203.0.113.7"],
        )

    def test_non_nginx_line_rejected(self):
        self.assertIsNone(self.parser.parse("2024-03-01 12:00:00 [auth] INFO hello"))


class MalformedInputTests(unittest.TestCase):
    def test_malformed_fixture_does_not_crash_processing(self):
        aggregator = LogAggregator()
        count = aggregator.process_file(str(FIXTURES_DIR / "malformed_logs.log"))
        # 4 non-blank lines are accepted (generic text / coerced JSON); blank skipped.
        self.assertEqual(count, 4)

    def test_bad_json_timestamp_coerced_without_raising(self):
        line = '{"timestamp": "not-a-date", "level": "INFO", "service": "x", "message": "bad"}'
        aggregator = LogAggregator()
        self.assertTrue(aggregator._parse_line(line))

    def test_non_finite_timestamps_do_not_raise(self):
        parser = JSONLogParser()
        for raw in ("inf", "-inf", "Infinity", "1e400"):
            self.assertIsNone(parser.coerce_timestamp(raw))
        self.assertIsNone(parser.coerce_timestamp(float("inf")))
        self.assertIsNone(parser.coerce_timestamp(float("nan")))

    def test_specific_parsers_reject_unsupported_lines(self):
        self.assertIsNone(JSONLogParser().parse("!!! ??? ### not a structured record"))
        self.assertIsNone(NginxLogParser().parse("random unparseable garbage line"))
        self.assertIsNone(TextLogParser().parse(""))


class AggregatorFixtureTests(unittest.TestCase):
    def test_nginx_fixture_parsed_as_nginx_not_swallowed_by_text(self):
        aggregator = LogAggregator()
        count = aggregator.process_file(str(FIXTURES_DIR / "nginx_logs.log"))
        self.assertEqual(count, 4)
        self.assertEqual({e["format"] for e in aggregator.entries}, {"nginx"})
        self.assertEqual(aggregator.service_counts.get("nginx"), 4)
        self.assertEqual(aggregator.level_counts.get("warn"), 1)
        self.assertEqual(aggregator.level_counts.get("error"), 1)

    def test_json_fixture_aggregates_all_lines(self):
        aggregator = LogAggregator()
        count = aggregator.process_file(str(FIXTURES_DIR / "json_logs.log"))
        self.assertEqual(count, 4)
        summary = aggregator.get_summary()
        self.assertEqual(summary["total_entries"], 4)
        self.assertEqual(summary["by_service"]["auth"], 1)
        self.assertTrue(all(e["timestamp"] for e in aggregator.entries))

    def test_text_fixture_aggregates(self):
        aggregator = LogAggregator()
        count = aggregator.process_file(str(FIXTURES_DIR / "text_logs.log"))
        self.assertEqual(count, 5)
        summary = aggregator.get_summary()
        self.assertEqual(summary["total_entries"], 5)


class CLITests(unittest.TestCase):
    def _run_cli(self, *args):
        return subprocess.run(
            [sys.executable, str(TOOLS_DIR / "log_aggregator.py"), *args],
            capture_output=True,
            text=True,
        )

    def test_cli_json_output_for_nginx_fixture(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "report.json"
            result = self._run_cli(
                "--input",
                str(FIXTURES_DIR / "nginx_logs.log"),
                "--output",
                str(out),
                "--format",
                "json",
            )
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertTrue(out.exists())
            report = json.loads(out.read_text(encoding="utf-8"))
            self.assertEqual(report["summary"]["total_entries"], 4)
            self.assertEqual(report["summary"]["by_service"].get("nginx"), 4)

    def test_cli_handles_logs_without_timestamps(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "report.json"
            result = self._run_cli(
                "--input",
                str(FIXTURES_DIR / "malformed_logs.log"),
                "--output",
                str(out),
                "--format",
                "json",
            )
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertIn("Time range: N/A to N/A", result.stdout)

    def test_cli_csv_output_compatible(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "report.csv"
            result = self._run_cli(
                "--input",
                str(FIXTURES_DIR / "text_logs.log"),
                "--output",
                str(out),
                "--format",
                "csv",
            )
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertTrue(out.exists())
            self.assertEqual(out.read_text(encoding="utf-8").splitlines()[0], "timestamp,level,service,message")


if __name__ == "__main__":
    unittest.main()
