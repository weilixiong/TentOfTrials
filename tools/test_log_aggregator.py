class MalformedLineTests(unittest.TestCase):
    """Unsupported lines are skipped or downgraded, never raised on."""

    def test_malformed_lines_do_not_crash(self):
        json_parser = JSONLogParser()
        text_parser = TextLogParser()
        nginx_parser = NginxLogParser()
        for fixture in MALFORMED_FIXTURES:
            with self.subTest(fixture=fixture["name"]):
                line = fixture["line"]
                json_entry = json_parser.parse(line)
                text_entry = text_parser.parse(line)
                nginx_entry = nginx_parser.parse(line)
                self.assertEqual(json_entry is not None, fixture["json_parses"])
                self.assertEqual(text_entry is not None, fixture["text_parses"])
                if text_entry is not None:
                    self.assertEqual(text_entry["format"], "text")
                    self.assertIsInstance(text_entry["message"], str)
                self.assertIsNone(nginx_entry)

    def test_malformed_lines_do_not_break_the_aggregator(self):
        aggregator = LogAggregator()
        for fixture in MALFORMED_FIXTURES:
            with self.subTest(fixture=fixture["name"]):
                self.assertIsInstance(aggregator._parse_line(fixture["line"]), bool)


class AggregatorCompatibilityTests(unittest.TestCase):
    """The aggregation behaviour and the CLI output must stay compatible."""

    def setUp(self):
        self.lines = [f["line"] for f in JSON_FIXTURES + TEXT_FIXTURES + NGINX_FIXTURES]

    def test_aggregator_counts_match_the_fixture_expectations(self):
        aggregator = LogAggregator()
        for line in self.lines:
            self.assertTrue(aggregator._parse_line(line))

        summary = aggregator.get_summary()
        self.assertEqual(summary["total_entries"], len(self.lines))
        # The aggregator tries the JSON parser, then the text parser, then the
        # nginx parser.  The text parser accepts every non-empty line, so the
        # nginx access lines are counted as generic text entries today and the
        # nginx parser is only reached when it is used directly.
        self.assertEqual(
            summary["by_level"],
            {"error": 2, "warn": 2, "info": 2, "debug": 2, "unknown": 5},
        )
        self.assertEqual(
            summary["by_service"],
            {
                "checkout": 2, "auth": 2, "billing": 2, "scheduler": 1,
                "worker": 1, "PAYMENTS": 1, "gateway": 1, None: 3,
            },
        )
        self.assertEqual(summary["error_rate"], 15.38)

    def test_nginx_parser_is_exercised_directly(self):
        """The nginx parser keeps working when it is used on its own.

        The aggregator currently routes nginx lines through the text parser,
        because the text parser accepts every non-empty line.  Reordering the
        parser list would change the CLI output, so that decision is left to
        the maintainer; this test pins the current routing.
        """
        entry = NginxLogParser().parse(NGINX_FIXTURES[0]["line"])
        self.assertEqual(entry["format"], "nginx")
        self.assertEqual(entry["service"], "nginx")

        aggregator = LogAggregator()
        aggregator._parse_line(NGINX_FIXTURES[0]["line"])
        self.assertEqual(aggregator.entries[0]["format"], "text")

    def test_cli_report_stays_compatible(self):
        with tempfile.TemporaryDirectory() as tmp:
            log_path = os.path.join(tmp, "fixtures.log")
            report_path = os.path.join(tmp, "report.json")
            with open(log_path, "w", encoding="utf-8") as handle:
                handle.write("\n".join(self.lines) + "\n")

            result = subprocess.run(
                [sys.executable, str(_HERE / "log_aggregator.py"), "--input", log_path, "--output", report_path],
                capture_output=True,
                text=True,
            )
            self.assertEqual(result.returncode, 0, result.stderr)

            with open(report_path, "r", encoding="utf-8") as handle:
                report = json.load(handle)

            self.assertIn("summary", report)
            self.assertIn("error_timeline", report)
            self.assertIn("service_breakdown", report)
            self.assertIn("entries", report)
            self.assertEqual(report["summary"]["total_entries"], len(self.lines))
            self.assertEqual(len(report["entries"]), len(self.lines))
            self.assertEqual(
                report["summary"]["by_level"],
                {"error": 2, "warn": 2, "info": 2, "debug": 2, "unknown": 5},
            )
            self.assertEqual(report["summary"]["by_service"]["checkout"], 2)


