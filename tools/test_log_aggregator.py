class JSONFixtureTests(unittest.TestCase):
    """Structured JSON lines must map onto the aggregator entry shape."""

    def test_json_fixtures(self):
        parser = JSONLogParser()
        for fixture in JSON_FIXTURES:
            with self.subTest(fixture=fixture["name"]):
                entry = parser.parse(fixture["line"])
                self.assertIsNotNone(entry)
                self.assertEqual(entry["format"], "json")
                self.assertEqual(entry["timestamp"], fixture["timestamp"])
                self.assertEqual(entry["level"], fixture["level"])
                self.assertEqual(entry["service"], fixture["service"])
                self.assertEqual(entry["message"], fixture["message"])
                for key, value in fixture["field_checks"].items():
                    self.assertIn(key, entry["fields"])
                    self.assertEqual(entry["fields"][key], value)

    def test_json_fields_keep_the_original_payload(self):
        entry = JSONLogParser().parse(JSON_FIXTURES[0]["line"])
        self.assertEqual(entry["fields"]["message"], "payment gateway timeout")
        self.assertEqual(entry["fields"]["order_id"], 88123)
        self.assertEqual(entry["fields"]["timestamp"], "2026-11-15T10:23:45Z")


