# ---------------------------------------------------------------------------
# Helper: compute expected epoch timestamps independently
# ---------------------------------------------------------------------------

def _epoch(dt_str: str, fmt: str = "%Y-%m-%dT%H:%M:%S") -> int:
    """Convert a human timestamp to UTC epoch seconds (independent of parser)."""
    dt = datetime.strptime(dt_str, fmt)
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return int(dt.timestamp())


# Pre-computed expected timestamps (computed here, NOT from the parser)
EXPECTED_TS_10_30_00 = _epoch("2024-03-15T10:30:00")
EXPECTED_TS_11_45_22 = _epoch("2024-03-15T11:45:22")
EXPECTED_TS_08_15_03 = _epoch("2024-03-15T08:15:03")
EXPECTED_TS_14_22_10 = _epoch("2024-03-15 14:22:10", "%Y-%m-%d %H:%M:%S")


