class TestMalformedAndAggregator(unittest.TestCase):
    """Malformed-line resilience + aggregator integration tests."""

    def test_aggregator_does_not_crash_on_malformed(self):
        """All malformed fixtures must be processed without raising."""
        agg = LogAggregator()
        for line in [MALFORMED_FIXTURE_1, MALFORMED_FIXTURE_2, MALFORMED_FIXTURE_3]:
            # _parse_line returns False for unparsable lines but must not raise
            result = agg._parse_line(line)
            # Garbled text may still match TextLogParser (it parses anything non-empty);
            # the key requirement is: no crash.
            self.assertIsInstance(result, bool)

    def test_aggregator_processes_mixed_formats(self):
        """Aggregator should handle JSON, text, and nginx lines together."""
        agg = LogAggregator()
        all_lines = [
            JSON_FIXTURE_1,
            JSON_FIXTURE_2,
            JSON_FIXTURE_3,
            TEXT_FIXTURE_1,
            TEXT_FIXTURE_2,
            TEXT_FIXTURE_3,
            NGINX_FIXTURE_1,
            NGINX_FIXTURE_2,
            NGINX_FIXTURE_3,
        ]
        for line in all_lines:
            agg._parse_line(line)

        self.assertEqual(len(agg.entries), 9)
        # Check level counts
        self.assertGreater(agg.level_counts["error"], 0)
        self.assertGreater(agg.level_counts["warn"], 0)
        self.assertGreater(agg.level_counts["info"], 0)
        # Check service counts include expected services
        services = set(agg.service_counts.keys())
        self.assertIn("nginx", services)
        self.assertIn("payment-gateway", services)

    def test_malformed_garbled_line_text_parser_does_not_crash(self):
        """The garbled line (fixture 10) will be caught by TextLogParser
        since TextLogParser parses any non-empty line.  Verify it produces
        a valid entry without crashing and has format='text'."""
        parser = TextLogParser()
        entry = parser.parse(MALFORMED_FIXTURE_1)
        # TextLogParser parses any non-empty stripped line, so this will be
        # an entry with unknown level — the point is it must not crash.
        self.assertIsNotNone(entry)
        self.assertEqual(entry["format"], "text")
        self.assertEqual(entry["level"], "unknown")


