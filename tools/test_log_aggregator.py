"""Independent parser fixtures for tools/log_aggregator.py.

Why this file exists
--------------------
The legacy parser tests were generated by the parser itself, so a regression in
the parser could rewrite its own expectations and still pass.  Every log line
and every expected value below was written by hand from representative
production log shapes:

  * the fixture lines are literal strings, never produced by LogParser.parse()
  * the expected timestamps are literal integers, never recomputed by the
    parser under test
  * the expectations cover the fields the aggregator actually consumes:
    timestamp, level, service/format and the key fields of each format

Run with:
    python3 tools/test_log_aggregator.py
    python3 -m unittest discover -s tools -p "test_*.py"
"""

