#!/usr/bin/env python3
"""
Independent parser fixture tests for log_aggregator.py.

These tests use hand-written log fixture files (NOT generated by the parser)
to verify parser behavior independently.
"""

import os
import sys
import unittest
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from log_aggregator import JSONLogParser, TextLogParser, NginxLogParser, LogAggregator

FIXTURES_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "test_fixtures")


def read_fixture(name):
    path = os.path.join(FIXTURES_DIR, name)
    with open(path, 'r', encoding='utf-8') as f:
        return [line.rstrip('\n') for line in f]


class TestJSONParserFixtures(unittest.TestCase):
    """Test JSON log parser against hand-written fixtures."""

    @classmethod
    def setUpClass(cls):
        cls.lines = read_fixture("json_fixtures.log")
        cls.parser = JSONLogParser()
        cls.parsed = [cls.parser.parse(line) for line in cls.lines]

    def test_all_lines_parse(self):
        """All valid JSON fixture lines should parse successfully."""
        parsed_count = sum(1 for p in self.parsed if p is not None)
        self.assertEqual(parsed_count, len(self.lines),
                         f"Only {parsed_count}/{len(self.lines)} lines parsed")

    def test_timestamp_extraction(self):
        """Each parsed entry should have a timestamp."""
        for i, entry in enumerate(self.parsed):
            if entry:
                self.assertIsNotNone(entry.get('timestamp'),
                                     f"Line {i+1}: missing timestamp")

    def test_level_extraction(self):
        """Level should be extracted correctly from each entry."""
        expected_levels = [
            'info', 'debug', 'warn', 'error', 'info',
            'error', 'critical', 'info', 'debug', 'error',
        ]
        for i, (entry, expected) in enumerate(zip(self.parsed, expected_levels)):
            if entry:
                self.assertEqual(entry.get('level', '').lower(), expected,
                                 f"Line {i+1}: expected level '{expected}', got '{entry.get('level')}'")

    def test_service_extraction(self):
        """Service name should be extracted correctly."""
        expected_services = [
            'backend', 'backend', 'backend', 'backend', 'market',
            'backend', 'frailbox', 'frontend', 'backend', 'market',
        ]
        for i, (entry, expected) in enumerate(zip(self.parsed, expected_services)):
            if entry:
                self.assertEqual(entry.get('service', ''), expected,
                                 f"Line {i+1}: expected service '{expected}', got '{entry.get('service')}'")

    def test_format_marker(self):
        """All JSON entries should have format='json'."""
        for i, entry in enumerate(self.parsed):
            if entry:
                self.assertEqual(entry.get('format'), 'json',
                                 f"Line {i+1}: expected format 'json'")


