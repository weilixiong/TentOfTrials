class TestMalformedFixtures(unittest.TestCase):
    """Test parser resilience against malformed input."""

    @classmethod
    def setUpClass(cls):
        cls.lines = read_fixture("malformed_fixtures.log")
        cls.json_parser = JSONLogParser()
        cls.text_parser = TextLogParser()
        cls.nginx_parser = NginxLogParser()

    def test_no_crash_on_malformed(self):
        """Parsing malformed lines should never raise exceptions."""
        for i, line in enumerate(self.lines):
            for parser_name, parser in [('json', self.json_parser),
                                         ('text', self.text_parser),
                                         ('nginx', self.nginx_parser)]:
                try:
                    parser.parse(line)
                except Exception as e:
                    self.fail(f"Line {i+1} crashed {parser_name} parser: {e}")

    def test_malformed_lines_return_none(self):
        """Completely unstructured lines should return None (not crash)."""
        # Lines 0, 1, 3, 5, 6, 7 are malformed/unstructured
        for idx in [0, 1, 3, 5, 6, 7]:
            line = self.lines[idx] if idx < len(self.lines) else ''
            if not line.strip():
                continue
            result = self.json_parser.parse(line)
            # Should either not crash — None is fine
            self.assertIsNone(result or None)  # json parser returns None for non-json


class TestAggregatorWithFixtures(unittest.TestCase):
    """Test LogAggregator using fixture files end-to-end."""

    def test_aggregator_processes_json_fixtures(self):
        agg = LogAggregator()
        count = agg.process_file(os.path.join(FIXTURES_DIR, "json_fixtures.log"))
        self.assertEqual(count, 10, "Should parse all 10 JSON fixture lines")
        self.assertEqual(agg.level_counts.get('info', 0), 3)
        self.assertEqual(agg.level_counts.get('error', 0), 3)
        self.assertEqual(agg.level_counts.get('debug', 0), 2)
        self.assertEqual(agg.level_counts.get('warn', 0), 1)
        self.assertEqual(agg.level_counts.get('critical', 0), 1)

    def test_aggregator_processes_text_fixtures(self):
        agg = LogAggregator()
        count = agg.process_file(os.path.join(FIXTURES_DIR, "text_fixtures.log"))
        self.assertEqual(count, 10, "Should parse all 10 text fixture lines")

    def test_aggregator_processes_nginx_fixtures(self):
        agg = LogAggregator()
        count = agg.process_file(os.path.join(FIXTURES_DIR, "nginx_fixtures.log"))
        self.assertEqual(count, 10, "Should parse all 10 nginx fixture lines")

    def test_malformed_does_not_crash_aggregator(self):
        """The aggregator should not crash or count malformed lines."""
        agg = LogAggregator()
        count = agg.process_file(os.path.join(FIXTURES_DIR, "malformed_fixtures.log"))
        # Only the valid JSON line (index 4) should parse
        self.assertGreaterEqual(count, 0, "Aggregator should not crash on malformed input")
        # Verify no crash
        summary = agg.get_summary()
        self.assertIn('total_entries', summary)

    def test_mixed_fixtures_directory(self):
        """Process all fixtures at once."""
        agg = LogAggregator()
        total = agg.process_directory(FIXTURES_DIR, "*.log")
        self.assertGreaterEqual(total, 30, "Should parse at least 30 lines across all fixture files")
        summary = agg.get_summary()
        self.assertGreater(summary['total_entries'], 0)
        self.assertIn('by_level', summary)
        self.assertIn('by_service', summary)


if __name__ == "__main__":
    unittest.main()
